/**
 * Ten blog posts for the store.
 * Run it with: php artisan db:seed --class=PostSeeder
 *
 * It needs the admin user from DatabaseSeeder. A post is matched by its slug, so running it
 * again adds nothing and leaves edited posts alone; it only redraws the cover images.
 */
class PostSeeder extends Seeder
{
    public function run(): void
    {
        $admin = User::whereHas('roles', fn ($query) => $query->where('name', 'admin'))->firstOrFail();

        DB::transaction(function () use ($admin) {
            foreach ($this->posts() as $daysAgo => $data) {
                $post = Post::where('slug', $data['slug'])->first();

                if (! $post) {
                    $post = Post::create([
                        'title' => $data['title'],
                        'slug' => $data['slug'],
                        'content' => implode("\n\n", $data['paragraphs']),
                        'status' => 'published',
                        'user_id' => $admin->id,
                    ]);

                    $post->forceFill(['created_at' => now()->subDays($daysAgo * 3)])->save();
                    $post->tags()->syncWithoutDetaching($this->tagIds($data['tags']));
                }

                $this->saveCover($post, $data);
            }
        });
    }

    /**
     * @param  array<string, string>  $tags  English name => Arabic name
     */
    private function tagIds(array $tags): array
    {
        return collect($tags)
            ->map(fn ($nameAr, $nameEn) => Tag::firstOrCreate(
                ['name_en' => $nameEn],
                ['name_ar' => $nameAr, 'slug' => str($nameEn)->slug()->toString()],
            )->id)
            ->values()
            ->all();
    }

    private function saveCover(Post $post, array $data): void
    {
        $path = "posts/seed/{$post->slug}.svg";
        $drawing = strtr(file_get_contents(__DIR__."/images/{$data['image']}.svg.stub"), [
            '{main}' => $data['color'],
            '{dark}' => '#081828',
        ]);

        Storage::disk('public')->put($path, <<<SVG
        <svg xmlns="http://www.w3.org/2000/svg" width="850" height="460" viewBox="0 0 850 460">
        <defs><linearGradient id="bg" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="#081828"/><stop offset="1" stop-color="#123a6b"/></linearGradient></defs>
        <rect width="850" height="460" fill="url(#bg)"/>
        <circle cx="425" cy="230" r="205" fill="#ffffff" opacity="0.1"/>
        <g transform="translate(209 14) scale(0.72)">{$drawing}</g>
        </svg>
        SVG);

        $post->images()->firstOrCreate(['image' => $path], ['alt' => $post->title, 'is_primary' => true]);
    }

